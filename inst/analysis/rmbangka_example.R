library(subpure); data(rmbangka)
items <- names(rmbangka)[7:42]
facets <- split(items, substr(items,1,1)); names(facets) <- c("NC","TOL","AV","ALC")
method <- c('A2','A3','A6','A7','A10','B12','B14','B16','B19','C21','C22','C25','C26','C29','C30','D32','D34','D36')
rmbangka$faith <- factor(ifelse(rmbangka$religion=="Islam","Muslim","Non-Muslim"))
t0<-Sys.time()
pf <- pure_fit(rmbangka, facets, method); print(pf)
pv <- pure_value(rmbangka, facets, method, R=1000, seed=20261112); print(pv)
pg <- pure_value(rmbangka, facets, method, group="faith", R=1000, seed=20261112); print(pg)
ps <- pure_value(rmbangka, facets, method, group="school_type", R=1000, seed=20261112); print(ps)
print(Sys.time()-t0)
saveRDS(list(pf=pf$table,pv=pv[c('facets','global','misattribution')],pg=pg[c('facets','global','contrasts')],ps=ps[c('facets','global','contrasts')]),'real_results.rds')
